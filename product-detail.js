function getQueryParam(name) {
  return new URLSearchParams(window.location.search).get(name);
}

function renderProduct(product) {
  document.title = `${product.name} | Citrus Grove`;
  document.getElementById('productName').textContent = product.name;
  document.getElementById('productPrice').textContent = product.price;
  document.getElementById('productCategory').textContent = product.category;
  document.getElementById('productDescription').textContent = product.description;
  document.getElementById('productAvailability').textContent = product.availability;
  document.getElementById('productMaterial').textContent = product.material;
  const image = document.getElementById('productImage');
  image.src = product.image;
  image.alt = product.alt;
  const featuresList = document.getElementById('productFeatures');
  featuresList.innerHTML = product.details.map(item => `<li>${item}</li>`).join('');
}

function getCart() {
  const storedCart = localStorage.getItem('citrusGroveCart');
  return storedCart ? JSON.parse(storedCart) : [];
}

function saveCart(cart) {
  localStorage.setItem('citrusGroveCart', JSON.stringify(cart));
}

function addToCart(productKey) {
  const cart = getCart();
  const existingItem = cart.find(item => item.slug === productKey);
  if (existingItem) {
    existingItem.quantity += 1;
  } else {
    const product = productData[productKey];
    cart.push({
      slug: productKey,
      quantity: 1,
      name: product.name,
      price: product.price,
      category: product.category,
      image: product.image,
      alt: product.alt
    });
  }
  saveCart(cart);
  const messageNode = document.getElementById('cartMessage');
  if (messageNode) {
    messageNode.textContent = 'Product added to cart. You can continue shopping or view your cart.';
  }
  if (window.updateCartCount) {
    window.updateCartCount();
  }
}

function showMissing() {
  document.getElementById('detailContent').innerHTML = `
    <div class="missing-product">
      <h2>Product not found</h2>
      <p>We couldn't find that item. Please return to the products page and select a different product.</p>
      <a class="btn btn-secondary" href="products.html">Back to products</a>
    </div>
  `;
}

window.addEventListener('DOMContentLoaded', () => {
  const productKey = getQueryParam('product');
  if (productKey && productData[productKey]) {
    renderProduct(productData[productKey]);
    const addButton = document.getElementById('addToCart');
    if (addButton) {
      addButton.addEventListener('click', () => addToCart(productKey));
    }
  } else {
    showMissing();
  }
});

